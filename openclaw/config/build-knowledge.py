def extract_section(file_path: Path, max_chars: int = 1500) -> str:
    """Безопасно читает текстовый файл и возвращает его начало с обрезкой."""
    if not file_path.exists():
        return ""
    try:
        content = file_path.read_text(encoding="utf-8")
        if len(content) > max_chars:
            return content[:max_chars] + "\n\n... (подробности см. в файле)\n"
        return content
    except Exception as e:
        return f"Ошибка чтения {file_path.name}: {e}"


