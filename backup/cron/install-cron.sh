#!/usr/bin/env bash
# ==============================================================================
# Скрипт безопасной установки/обновления cron-задач на сервере Huawei
#
# Синхронизирует эталонный файл huawei.crontab в планировщик задач пользователя huawei.
# ==============================================================================

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
CRON_FILE="${SCRIPT_DIR}/huawei.crontab"
SERVER="huawei@100.92.50.18"

echo "======================================================================"
echo "⚙️ Установка cron-расписания бэкапов на сервере Huawei..."
echo "======================================================================"

if [ ! -f "${CRON_FILE}" ]; then
  echo "❌ Файл ${CRON_FILE} не найден!"
  exit 1
fi

# Проверяем, запущен ли скрипт прямо на целевом сервере или удаленно
if [ "$(id -un 2>/dev/null || whoami)" = "huawei" ]; then
  # Запуск локально на сервере Huawei
  crontab "${CRON_FILE}"
  echo "✅ Crontab успешно обновлен локально на сервере Huawei!"
  echo "📋 Текущие задачи crontab:"
  crontab -l
else
  # Запуск удаленно с локального компьютера (Mac)
  ssh "${SERVER}" "crontab -" < "${CRON_FILE}"
  echo "✅ Crontab успешно обновлен на сервере Huawei!"
  echo "📋 Текущие задачи crontab на сервере:"
  ssh "${SERVER}" "crontab -l"
fi
echo "======================================================================"
