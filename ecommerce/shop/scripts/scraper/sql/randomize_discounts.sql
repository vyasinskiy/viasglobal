-- Скрипт обновления скидок в PostgreSQL
-- ~22% товаров получают реалистичный размер скидки (-10% .. -25%)
-- У остальных 78% товаров зачеркнутая цена original_price сбрасывается в NULL

UPDATE products
SET original_price = CASE 
  -- Для ~22% товаров назначаем акционную зачеркнутую цену с разным коэффициентом
  WHEN (('x' || substr(md5(id), 1, 4))::bit(16)::int % 100) < 22 
  THEN round(price * (
    CASE (('x' || substr(md5(id), 5, 2))::bit(8)::int % 4)
      WHEN 0 THEN 1.12  -- ~11% скидка
      WHEN 1 THEN 1.18  -- ~15% скидка
      WHEN 2 THEN 1.25  -- ~20% скидка
      ELSE 1.33         -- ~25% скидка
    END
  )::numeric, 2)
  -- Для остальных 78% товаров зачеркнутая цена отсутствует (обычная цена)
  ELSE NULL
END;
