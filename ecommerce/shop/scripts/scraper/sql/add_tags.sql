-- ============================================================================
-- Миграция: Добавление поддержки тегов (tags) для товаров витрины
-- Позволяет группировать товары по сезонным подборкам ('playa', 'verano', 'colegio' и т.д.)
-- ============================================================================

-- 1. Добавляем массив строк tags в таблицу products
ALTER TABLE public.products 
ADD COLUMN IF NOT EXISTS tags text[] DEFAULT '{}'::text[];

-- 2. Создаем GIN индекс для мгновенного поиска и фильтрации товаров по тегам
CREATE INDEX IF NOT EXISTS idx_products_tags 
ON public.products USING GIN (tags);
